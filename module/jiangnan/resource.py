# ============================================================
# 普通资源位置
#
# 示例：
#
# WAREHOUSE_RESOURCE_POSITION['蔬菜']
#
# ->
#
# {
#     'row': 0,
#     'side': 'left'
# }
#
# 后面 OCR 纠错会使用这个信息。
# ============================================================

WAREHOUSE_RESOURCE_POSITION = {}

for row_index, row in enumerate(
    WAREHOUSE_RESOURCE_ROWS
):

    left, right = row

    if left is not None:

        WAREHOUSE_RESOURCE_POSITION[
            left
        ] = {
            'row': row_index,
            'side': 'left',
        }

    if right is not None:

        WAREHOUSE_RESOURCE_POSITION[
            right
        ] = {
            'row': row_index,
            'side': 'right',
        }


