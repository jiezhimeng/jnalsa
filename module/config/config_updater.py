class ConfigGenerator:
    @cached_property
    def argument(self):
        """
        Load argument.yaml, and standardise its structure.

        <group>:
            <argument>:
                type: checkbox|select|textarea|input
                value:
                option (Optional): Options, if argument has any options.
                validate (Optional): datetime
        """
        data = {}
        raw = read_file(filepath_argument('argument'))
        for path, value in deep_iter(raw, depth=2):
            arg = {
                'type': 'input',
                'value': '',
                # option
            }
            if not isinstance(value, dict):
                value = {'value': value}
            arg['type'] = data_to_type(value, arg=path[1])
            if isinstance(value['value'], datetime):
                arg['type'] = 'datetime'
                arg['validate'] = 'datetime'
            # Manual definition has the highest priority
            arg.update(value)
            deep_set(data, keys=path, value=arg)

        # Include every runnable Jiangnan task, across all menu categories.
        tasks = [
            name
            for category in self.task.values()
            for name, groups in category.get('tasks', {}).items()
            if name.startswith('Jiangnan') and 'Scheduler' in groups
        ]
        data['TaskPriority'] = {
            name: {
                'type': 'input', 'value': priority,
                'validate': r'[1-9][0-9]*',
            }
            for name, priority in priority_defaults(
                tasks, ManualConfig.SCHEDULER_PRIORITY
            ).items()
        }

        # Define storage group
        arg = {
            'type': 'storage',
            'value': {},
            'valuetype': 'ignore',
            'display': 'disabled',
        }
        deep_set(data, keys=['Storage', 'Storage'], value=arg)
